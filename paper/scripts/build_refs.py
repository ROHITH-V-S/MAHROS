"""Build paper/refs.tex: the IEEE-formatted bibliography, grouped by type.

    1. pdflatex main            (writes main.aux with the citations)
    2. python scripts/build_refs.py aux      (writes refs_tmp.aux)
    3. bibtex refs_tmp           (formats with IEEEtran.bst -> refs_tmp.bbl)
    4. python scripts/build_refs.py group    (writes refs.tex)
    5. pdflatex main; pdflatex main

Groups: Weblinks and Datasets, Journals, Conference Papers, Books, Reports
and Preprints. Within a group, entries keep the order of first citation;
numbering runs continuously across groups.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parents[1]

GROUPS = [
    ("Weblinks and Datasets", "misc_web"),
    ("Journals", "article"),
    ("Conference Papers", "inproceedings"),
    ("Books, Reports and Preprints", "other"),
]


def bib_types() -> dict[str, str]:
    text = (HERE / "references.bib").read_text(encoding="utf-8")
    out = {}
    for typ, key in re.findall(r"@(\w+)\s*\{\s*([^,\s]+)\s*,", text):
        typ = typ.lower()
        body = text[text.index(key):text.index(key) + 1200]
        if typ == "misc" and "archivePrefix" not in body.split("\n@")[0]:
            out[key] = "misc_web"
        elif typ == "techreport" and "gao" in key:
            out[key] = "misc_web"
        elif typ in ("article", "inproceedings"):
            out[key] = typ
        else:
            out[key] = "other"
    return out


def cited_keys() -> list[str]:
    aux = (HERE / "main.aux").read_text(encoding="utf-8")
    seen, order = set(), []
    for group in re.findall(r"\\citation\{([^}]*)\}", aux):
        for k in group.split(","):
            k = k.strip()
            if k and k not in seen:
                seen.add(k)
                order.append(k)
    return order


def write_aux() -> None:
    keys = cited_keys()
    (HERE / "refs_tmp.aux").write_text(
        "".join(f"\\citation{{{k}}}\n" for k in keys)
        + "\\bibstyle{IEEEtran}\n\\bibdata{references}\n", encoding="utf-8")
    print(f"refs_tmp.aux: {len(keys)} cited keys")


def group() -> None:
    bbl = (HERE / "refs_tmp.bbl").read_text(encoding="utf-8")
    head, _, rest = bbl.partition("\\bibitem")
    head = head.replace("\\begin{thebibliography}{1}", "").strip()
    body = rest.rsplit("\\end{thebibliography}", 1)[0]
    items = {}
    for chunk in ("\\bibitem" + body).split("\\bibitem")[1:]:
        m = re.match(r"\{([^}]+)\}", chunk)
        items[m.group(1)] = "\\bibitem" + chunk.rstrip() + "\n"
    order = cited_keys()
    types = bib_types()
    lines = ["% Generated by scripts/build_refs.py -- do not edit by hand.",
             head.replace("\\begin{thebibliography}", "%"),
             "\\begin{thebibliography}{99}"]
    for title, tag in GROUPS:
        keys = [k for k in order if types.get(k) == tag and k in items]
        if not keys:
            continue
        lines.append(f"\\refgroup{{{title}}}")
        lines.extend(items[k] for k in keys)
    lines.append("\\end{thebibliography}")
    (HERE / "refs.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    missing = [k for k in order if k not in items]
    print(f"refs.tex: {len(order) - len(missing)} entries; missing: {missing}")


if __name__ == "__main__":
    {"aux": write_aux, "group": group}[sys.argv[1]]()
